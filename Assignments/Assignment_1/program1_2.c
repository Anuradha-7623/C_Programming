// program to print "Marvellous" 5 times on screen


#include <stdio.h> 

// Function to print "Marvellous" 5 times
void Display()
{
int i = 0; // Variable declaration

// Loop executes five times
for (i = 1; i <= 5; i++)
{
    printf("Marvellous\n");  // Display 
}

}

// Main function
int main()
{
Display(); // Call the Display function

return 0;  // Indicate successful execution

}
